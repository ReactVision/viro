package com.viromedia.bridge.module;

import android.app.Activity;
import android.app.Application;
import android.app.PendingIntent;
import android.content.Context;
import android.content.Intent;
import android.content.pm.PackageManager;
import android.os.Bundle;
import android.os.Handler;
import android.os.Looper;
import android.util.Log;

import com.facebook.react.bridge.Arguments;
import com.facebook.react.bridge.Promise;
import com.facebook.react.bridge.ReactApplicationContext;
import com.facebook.react.bridge.ReactContextBaseJavaModule;
import com.facebook.react.bridge.ReactMethod;
import com.facebook.react.bridge.ReadableArray;
import com.facebook.react.bridge.WritableMap;
import com.facebook.react.internal.featureflags.ReactNativeFeatureFlags;
import com.facebook.react.internal.featureflags.ReactNativeFeatureFlagsDefaults;
import com.facebook.react.modules.core.PermissionAwareActivity;

/**
 * VRLauncherModule
 *
 * Registered by ReactViroPackage when ViroPlatform.QUEST is active.
 * Launches a VRActivity (generated by the withViroAndroid Expo plugin) that
 * carries com.oculus.intent.category.VR, causing Horizon OS to grant exclusive
 * OpenXR display access for stereo VR rendering.
 *
 * JS usage:
 *   import { NativeModules } from 'react-native';
 *   NativeModules.VRLauncher?.launchVRScene();
 */
public class VRLauncherModule extends ReactContextBaseJavaModule {

    private static final String MODULE_NAME = "VRLauncher";
    // Component name that VRActivity will mount.
    // Must match AppRegistry.registerComponent("VRQuestScene", ...) in the app's entry.
    private static final String VR_COMPONENT = "VRQuestScene";
    private static final int PERMISSIONS_REQUEST_CODE = 0x5652;

    /** Sent to JavaScript when a VRActivity starts finishing. See notifyFinishing. */
    private static final String EVENT_VR_ACTIVITY_FINISHING = "ViroVRActivityFinishing";
    /**
     * How long a launch waits for a finishing VRActivity to be destroyed before it goes
     * ahead anyway. Android destroys a finished activity once the next one is idle,
     * normally well inside a second.
     */
    private static final long LAUNCH_WAIT_FOR_DESTROY_MS = 4000;

    private final Handler mMainHandler = new Handler(Looper.getMainLooper());
    private Application.ActivityLifecycleCallbacks mLifecycleCallbacks;
    /** VRActivities JavaScript has been told are finishing. Main thread only. */
    private final java.util.Set<Activity> mNotifiedFinishing =
        java.util.Collections.newSetFromMap(new java.util.WeakHashMap<Activity, Boolean>());
    /** A launch held back until the finishing VRActivity is destroyed. Main thread only. */
    private boolean mLaunchPending = false;
    private final Runnable mLaunchTimeout = () -> {
        if (!mLaunchPending) return;
        Log.w(MODULE_NAME, "A finishing VRActivity was not destroyed within "
            + LAUNCH_WAIT_FOR_DESTROY_MS + " ms; launching the headset view anyway");
        mLaunchPending = false;
        startVRActivity();
    };
    private final Runnable mCheckFinishing = this::notifyFinishing;

    public VRLauncherModule(ReactApplicationContext reactContext) {
        super(reactContext);
    }

    @Override
    public void initialize() {
        super.initialize();
        Context app = getReactApplicationContext().getApplicationContext();
        if (!(app instanceof Application)) return;
        // VRActivity finishes itself (the generated activity does, when another of the
        // app's activities resumes) and is finished by the system, as well as through
        // exitVRScene(). No callback reports finish() itself, so look for a finishing
        // VRActivity after each resume and pause, once the other callbacks have run.
        mLifecycleCallbacks = new Application.ActivityLifecycleCallbacks() {
            @Override public void onActivityResumed(Activity a) { mMainHandler.post(mCheckFinishing); }
            @Override public void onActivityPaused(Activity a) { mMainHandler.post(mCheckFinishing); }
            @Override public void onActivityDestroyed(Activity a) {
                if (isVRActivity(a)) mMainHandler.post(VRLauncherModule.this::launchIfClear);
            }
            @Override public void onActivityCreated(Activity a, Bundle b) {}
            @Override public void onActivityStarted(Activity a) {}
            @Override public void onActivityStopped(Activity a) {}
            @Override public void onActivitySaveInstanceState(Activity a, Bundle b) {}
        };
        ((Application) app).registerActivityLifecycleCallbacks(mLifecycleCallbacks);
    }

    @Override
    public void invalidate() {
        Context app = getReactApplicationContext().getApplicationContext();
        if (mLifecycleCallbacks != null && app instanceof Application) {
            ((Application) app).unregisterActivityLifecycleCallbacks(mLifecycleCallbacks);
        }
        mLifecycleCallbacks = null;
        mMainHandler.removeCallbacksAndMessages(null);
        super.invalidate();
    }

    /**
     * Tells JavaScript about each VRActivity that has started finishing, once. Its React
     * surface is only unloaded in onDestroy, which comes later, and until then its
     * ViroQuestEntryPoint is still mounted: without this it would answer the next
     * headset view's intent by mounting a second navigator in the dying activity.
     * Main thread.
     */
    private void notifyFinishing() {
        boolean any = false;
        for (Activity act : vrActivities(true)) {
            if (act.isFinishing() && mNotifiedFinishing.add(act)) {
                any = true;
            }
        }
        if (!any) return;
        ReactApplicationContext ctx = getReactApplicationContext();
        if (ctx.hasActiveReactInstance()) {
            ctx.emitDeviceEvent(EVENT_VR_ACTIVITY_FINISHING, null);
        }
    }

    @Override
    public String getName() {
        return MODULE_NAME;
    }

    @ReactMethod
    public void launchVRScene() {
        // Called from JS — Hermes is running and all startup feature flags are already
        // cached in C++. Setting dangerouslyForceOverride here is safe: it replaces the
        // C++ accessor with our Java-backed provider, but cached startup flags are
        // unaffected. skipActivityIdentityAssertionOnHostPause has not been read yet
        // (it is only read in ReactHostImpl.onHostPause, triggered after startActivity).
        try {
            ReactNativeFeatureFlags.INSTANCE.dangerouslyForceOverride(
                new ReactNativeFeatureFlagsDefaults() {
                    @Override
                    public boolean skipActivityIdentityAssertionOnHostPause() { return true; }
                    // dangerouslyForceOverride replaces the C++ provider, so all uncached
                    // reads now go through this provider. The Expo app uses ReactHost
                    // (bridgeless API) but dangerouslyForceOverride resets the JVM and C++
                    // caches. We must return true for enableBridgelessArchitecture so
                    // that ReactActivityDelegate.onCreate() and ReactDelegate.loadApp() /
                    // onHostResume() take the bridgeless path instead of the old-arch path.
                    // The Fabric and TurboModule flags no longer exist: both are always on.
                    @Override
                    public boolean enableBridgelessArchitecture() { return true; }
                }
            );
        } catch (Exception ignored) {}

        // Looked up here, so that a missing VRActivity is still reported to the caller
        // rather than thrown on the main thread.
        vrActivityClass();
        mMainHandler.post(() -> {
            mLaunchPending = true;
            launchIfClear();
        });
    }

    private Class<?> vrActivityClass() {
        ReactApplicationContext ctx = getReactApplicationContext();
        try {
            return Class.forName(ctx.getPackageName() + ".VRActivity");
        } catch (ClassNotFoundException e) {
            throw new RuntimeException(
                "VRActivity not found in package " + ctx.getPackageName() + ". " +
                "Ensure @reactvision/react-viro plugin is configured with xRMode: [\"QUEST\"] " +
                "and you have run expo prebuild."
            );
        }
    }

    /**
     * Starts VRActivity unless one is finishing and not yet destroyed. That one still
     * has its React surface mounted, and a second VRActivity started now would run
     * beside it. The launch then waits for onActivityDestroyed, or the timeout. A live
     * VRActivity that is not finishing is reused: it is singleTask. Main thread.
     */
    private void launchIfClear() {
        if (!mLaunchPending) return;
        for (Activity act : vrActivities(true)) {
            if (act.isFinishing()) {
                mMainHandler.removeCallbacks(mLaunchTimeout);
                mMainHandler.postDelayed(mLaunchTimeout, LAUNCH_WAIT_FOR_DESTROY_MS);
                Log.i(MODULE_NAME, "Holding the headset view launch until the finishing VRActivity is destroyed");
                return;
            }
        }
        mMainHandler.removeCallbacks(mLaunchTimeout);
        mLaunchPending = false;
        startVRActivity();
    }

    private void startVRActivity() {
        ReactApplicationContext ctx = getReactApplicationContext();
        try {
            Intent intent = new Intent(ctx, vrActivityClass());
            intent.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK);
            ctx.startActivity(intent);
        } catch (RuntimeException e) {
            Log.e(MODULE_NAME, "Could not start VRActivity", e);
        }
    }

    /**
     * Finish any live VRActivity in this process and return the user to the
     * app's panel (MainActivity) through Home.
     *
     * Why we don't use {@code getReactApplicationContext().getCurrentActivity()}:
     *   In dual-Activity Quest setups the ReactHost lifecycle is binary-state.
     *   {@code ReactHost.onHostResume(VRActivity)} doesn't refire if MainActivity
     *   already transitioned the host to RESUMED, so {@code currentActivity} on
     *   the React context can stay pointed at MainActivity even while VRActivity
     *   is foreground in the immersive compositor. Trusting it makes
     *   {@code finish()} target the wrong Activity (or a null one) and silently
     *   no-op, leaving the user stuck.
     *
     * Instead we walk {@code android.app.ActivityThread.mActivities} for live
     * Activities whose class is named "VRActivity" and finish each — same
     * reflection pattern used for host-Activity lookup in ViroViewOpenXR.
     *
     * JS usage:
     *   NativeModules.VRLauncher?.exitVRScene();
     */
    @ReactMethod
    public void exitVRScene() {
        new Handler(Looper.getMainLooper()).post(() -> {
            java.util.List<Activity> vrActivities = liveVRActivities();
            if (vrActivities.isEmpty()) return;
            launchPanelThroughHome(vrActivities.get(0));
            for (Activity act : vrActivities) {
                act.finish();
            }
            notifyFinishing();
        });
    }

    /**
     * Asks for runtime permissions through the live VRActivity, so Horizon OS
     * opens the prompt over the headset view. PermissionsAndroid asks through
     * the React context's current activity, which stays MainActivity while VR
     * runs (see exitVRScene): the prompt then opens over the panel, the headset
     * view closes, and VRActivity finishes when MainActivity resumes.
     *
     * Resolves each permission to "granted", "denied" or "never_ask_again", as
     * PermissionsAndroid.requestMultiple does, or null when no VRActivity is
     * live.
     */
    @ReactMethod
    public void requestPermissions(ReadableArray permissions, Promise promise) {
        new Handler(Looper.getMainLooper()).post(() -> {
            java.util.List<Activity> vrActivities = liveVRActivities();
            if (vrActivities.isEmpty() || !(vrActivities.get(0) instanceof PermissionAwareActivity)) {
                promise.resolve(null);
                return;
            }
            Activity vr = vrActivities.get(0);
            String[] names = new String[permissions.size()];
            for (int i = 0; i < names.length; i++) {
                names[i] = permissions.getString(i);
            }
            ((PermissionAwareActivity) vr).requestPermissions(names, PERMISSIONS_REQUEST_CODE,
                (requestCode, requested, grantResults) -> {
                    if (requestCode != PERMISSIONS_REQUEST_CODE) return false;
                    WritableMap results = Arguments.createMap();
                    for (int i = 0; i < names.length; i++) {
                        // A cancelled request returns no results.
                        if (i < grantResults.length && grantResults[i] == PackageManager.PERMISSION_GRANTED) {
                            results.putString(names[i], "granted");
                        } else if (vr.shouldShowRequestPermissionRationale(names[i])) {
                            results.putString(names[i], "denied");
                        } else {
                            results.putString(names[i], "never_ask_again");
                        }
                    }
                    promise.resolve(results);
                    return true;
                });
        });
    }

    /**
     * Live VRActivities, found through {@code ActivityThread.mActivities} (the
     * React context's current activity cannot be trusted, see exitVRScene).
     */
    static java.util.List<Activity> liveVRActivities() {
        return vrActivities(false);
    }

    private static boolean isVRActivity(Activity act) {
        return "VRActivity".equals(act.getClass().getSimpleName());
    }

    /** VRActivities not yet destroyed: the live ones, and the finishing ones if asked. */
    static java.util.List<Activity> vrActivities(boolean includeFinishing) {
        java.util.List<Activity> vrActivities = new java.util.ArrayList<>();
        try {
            Class<?> threadCls = Class.forName("android.app.ActivityThread");
            Object thread = threadCls.getMethod("currentActivityThread").invoke(null);
            java.lang.reflect.Field activitiesField = threadCls.getDeclaredField("mActivities");
            activitiesField.setAccessible(true);
            Object activities = activitiesField.get(thread);
            if (!(activities instanceof java.util.Map)) {
                return vrActivities;
            }
            for (Object record : ((java.util.Map<?, ?>) activities).values()) {
                java.lang.reflect.Field activityField = record.getClass().getDeclaredField("activity");
                activityField.setAccessible(true);
                Object a = activityField.get(record);
                if (!(a instanceof Activity)) continue;
                Activity act = (Activity) a;
                if (!isVRActivity(act)) continue;
                if (act.isDestroyed()) continue;
                if (act.isFinishing() && !includeFinishing) continue;
                vrActivities.add(act);
            }
        } catch (Throwable ignored) {}
        return vrActivities;
    }

    /**
     * Finishing VRActivity on its own lets Horizon OS place the app's panel
     * again, often away from where the wearer left it. Meta's hybrid-app sample
     * (HybridSample, launchPanelModeInHome) returns through Home instead, handing
     * it the panel as a pending intent. A failure here leaves the plain finish.
     */
    private static void launchPanelThroughHome(Activity from) {
        try {
            Intent panel = from.getPackageManager()
                .getLaunchIntentForPackage(from.getPackageName());
            if (panel == null) return;
            panel.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK);
            PendingIntent pendingPanel = PendingIntent.getActivity(
                from, 0, panel,
                PendingIntent.FLAG_UPDATE_CURRENT | PendingIntent.FLAG_IMMUTABLE
            );
            Intent home = new Intent(Intent.ACTION_MAIN)
                .addCategory(Intent.CATEGORY_HOME)
                .addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
                .putExtra("extra_launch_in_home_pending_intent", pendingPanel);
            from.startActivity(home);
        } catch (Throwable t) {
            Log.w(MODULE_NAME, "Could not return to the panel through Home", t);
        }
    }
}
